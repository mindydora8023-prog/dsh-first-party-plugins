#!/usr/bin/env node
/**
 * Zero-dependency pure-Node client bundle builder for DSH web plugins.
 *
 * WHY THIS EXISTS
 * DSH serves each plugin's `./client` export as a single classic script using
 * `window.__ModuleLoader__.load({ id, factory })`, without a Vite/esbuild step.
 * Large client halves (`session-meter`, `next-say`, `task-radar`) need modular
 * source files for maintainability and unit testing, while shipping one pure
 * ASCII, LF-only classic script in `lib/client.js`.
 *
 * MANIFEST FORMAT (`<plugin>/client/bundle.json`):
 *   {
 *     "template": "client/template.js",
 *     "output": "lib/client.js",
 *     "indent": "    ",
 *     "locales": { "source": "client/locales.json", "output": "lib/locales.js", "exportName": "LOCALES" },
 *     "blocks": [
 *       { "marker": "BLOCK_LOCALES", "source": "lib/locales.js" },
 *       { "marker": "BLOCK_MATCH", "source": "lib/match.js" }
 *     ]
 *   }
 *
 * Usage:
 *   node tools/build-client.mjs                  build every plugin with client/bundle.json
 *   node tools/build-client.mjs --check          verify every generated file is up to date
 *   node tools/build-client.mjs next-say         build one plugin
 *   node tools/build-client.mjs next-say --check check one plugin
 *
 * ASCII only: see the workspace AGENTS.md encoding rule.
 */

import fs from 'node:fs'
import path from 'node:path'
import vm from 'node:vm'
import { fileURLToPath } from 'node:url'

const WORKSPACE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

export class BuildError extends Error {
  constructor(message) {
    super(message)
    this.name = 'BuildError'
  }
}

/** Encode a JS string literal using pure ASCII (`\uXXXX` for non-ASCII). */
export function escapeAsciiString(text) {
  let out = '"'
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i]
    const code = text.charCodeAt(i)
    if (ch === '\\') out += '\\\\'
    else if (ch === '"') out += '\\"'
    else if (ch === '\n') out += '\\n'
    else if (ch === '\r') out += '\\r'
    else if (ch === '\t') out += '\\t'
    else if (code < 0x20 || code >= 0x7f) out += `\\u${code.toString(16).padStart(4, '0')}`
    else out += ch
  }
  return `${out}"`
}

/** Render a JSON-compatible value into deterministic, pure-ASCII JS source. */
function renderAsciiValue(value, level = 0) {
  const pad = '  '.repeat(level)
  const inner = '  '.repeat(level + 1)
  if (typeof value === 'string') return escapeAsciiString(value)
  if (value === null || typeof value === 'number' || typeof value === 'boolean') {
    return JSON.stringify(value)
  }
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]'
    return `[\n${value.map((item) => `${inner}${renderAsciiValue(item, level + 1)}`).join(',\n')},\n${pad}]`
  }
  if (typeof value === 'object') {
    const entries = Object.entries(value)
    if (entries.length === 0) return '{}'
    const lines = entries.map(([k, v]) => `${inner}${escapeAsciiString(k)}: ${renderAsciiValue(v, level + 1)}`)
    return `{\n${lines.join(',\n')},\n${pad}}`
  }
  throw new BuildError(`unsupported locale value type: ${typeof value}`)
}

/**
 * Render a pure-ASCII ESM locales module from a UTF-8 JSON dictionary.
 * Validates identical key sets across all top-level languages when present.
 */
export function renderLocalesModule(pluginRoot, localesSpec) {
  const sourcePath = path.join(pluginRoot, localesSpec.source)
  if (!fs.existsSync(sourcePath)) {
    throw new BuildError(`missing locale source ${localesSpec.source}`)
  }
  let parsed
  try {
    parsed = JSON.parse(fs.readFileSync(sourcePath, 'utf8'))
  } catch (error) {
    throw new BuildError(`invalid JSON in ${localesSpec.source}: ${error.message}`)
  }
  const langs = Object.keys(parsed)
  if (langs.length >= 2 && localesSpec.strictKeys !== false) {
    const baseline = Object.keys(parsed[langs[0]] ?? {}).sort()
    for (const lang of langs.slice(1)) {
      const keys = Object.keys(parsed[lang] ?? {}).sort()
      if (JSON.stringify(keys) !== JSON.stringify(baseline)) {
        const missing = baseline.filter((k) => !keys.includes(k))
        const extra = keys.filter((k) => !baseline.includes(k))
        throw new BuildError(
          `${localesSpec.source}: key mismatch in "${lang}" (missing: ${missing.join(', ') || 'none'}; extra: ${extra.join(', ') || 'none'})`,
        )
      }
    }
  }
  const exportName = localesSpec.exportName ?? 'LOCALES'
  const header = [
    '// Generated by tools/build-client.mjs from ' + localesSpec.source + '. Do not edit by hand.',
    '// Pure ASCII: non-ASCII characters are \\uXXXX escaped.',
    '',
  ].join('\n')
  const extra = localesSpec.exportDefault ? `\nexport default ${exportName};\n` : ''
  const rendered = `${header}export const ${exportName} = ${renderAsciiValue(parsed, 0)};\n${extra}`
  return assertCleanOutput(rendered, localesSpec.output)
}

/** Turn a plain-declaration ES module into an inlineable block of statements. */
export function stripModuleSyntax(source, label = 'module') {
  let text = source.replace(/\r\n/g, '\n')
  // Drop leading docblock: the generated bundle carries its own header.
  text = text.replace(/^\/\*\*[\s\S]*?\*\/\s*/, '')
  // Drop import statements (single-line or multi-line).
  text = text.replace(/^import\s+(?:[\s\S]*?\s+from\s+)?['"][^'"]+['"];?\s*$/gm, '')
  // Strip `export` keyword from declarations.
  text = text.replace(/^export\s+(async\s+)?(function|const|class|let|var)\s/gm, '$1$2 ')
  // Drop `export { ... }` re-export lists (single-line or multi-line).
  text = text.replace(/^export\s+\{[\s\S]*?\};?\s*$/gm, '')
  if (/^\s*export\b/m.test(text)) {
    throw new BuildError(
      `${label}: still contains an \`export\` after inlining (export default?); keep exports to \`export function|const|class\` or \`export { ... }\``,
    )
  }
  return text.trim()
}

function indentBlock(source, prefix) {
  if (!prefix) return source
  return source
    .split('\n')
    .map((line) => (line.trim().length > 0 ? `${prefix}${line}` : line))
    .join('\n')
}

function assertCleanOutput(text, label) {
  if (text.includes('\r')) {
    throw new BuildError(`${label}: generated file contains CR; refusing to write CRLF`)
  }
  const lines = text.split('\n')
  const offenders = []
  for (let i = 0; i < lines.length && offenders.length < 10; i += 1) {
    if (/[^\x00-\x7f]/.test(lines[i])) {
      offenders.push(`non-ASCII at line ${i + 1}: ${lines[i].slice(0, 120)}`)
    }
  }
  if (offenders.length > 0) {
    throw new BuildError(`${label}:\n${offenders.join('\n')}`)
  }
  return `${text.replace(/\s+$/, '')}\n`
}

/** Validate classic script syntax in-process via vm.Script (zero subprocess cost). */
function assertValidScriptSyntax(code, filename) {
  try {
    // eslint-disable-next-line no-new
    new vm.Script(code, { filename })
  } catch (error) {
    throw new BuildError(`${filename}: syntax error in generated bundle: ${error.message}`)
  }
}

/** Describe the first line difference between expected and actual text. */
export function describeDifference(expected, actual) {
  const expLines = expected.split('\n')
  const actLines = actual.split('\n')
  const messages = []
  if (expLines.length !== actLines.length) {
    messages.push(`line count: expected ${expLines.length}, found ${actLines.length}`)
  }
  const limit = Math.min(expLines.length, actLines.length)
  for (let i = 0; i < limit; i += 1) {
    if (expLines[i] !== actLines[i]) {
      messages.push(`first difference at line ${i + 1}:`)
      messages.push(`  expected: ${JSON.stringify(expLines[i].slice(0, 160))}`)
      messages.push(`  found   : ${JSON.stringify(actLines[i].slice(0, 160))}`)
      return messages
    }
  }
  if (messages.length === 0) {
    messages.push(
      `same lines but different bytes: expected ${Buffer.byteLength(expected, 'utf8')} bytes, found ${Buffer.byteLength(actual, 'utf8')}`,
    )
  }
  return messages
}

/**
 * Render all generated outputs for one plugin in memory.
 * @param {string} pluginRoot
 * @returns {{manifest: object, files: Array<{rel: string, content: string}>}}
 */
export function renderPluginBundle(pluginRoot) {
  const manifestPath = path.join(pluginRoot, 'client', 'bundle.json')
  if (!fs.existsSync(manifestPath)) {
    throw new BuildError(`missing ${manifestPath}`)
  }
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
  const files = []
  const virtual = new Map()

  if (manifest.locales) {
    const content = renderLocalesModule(pluginRoot, manifest.locales)
    files.push({ rel: manifest.locales.output, content })
    virtual.set(manifest.locales.output.replace(/\\/g, '/'), content)
  }

  const templatePath = path.join(pluginRoot, manifest.template)
  if (!fs.existsSync(templatePath)) {
    throw new BuildError(`missing template ${manifest.template}`)
  }
  let built = fs.readFileSync(templatePath, 'utf8').replace(/\r\n/g, '\n')
  const defaultIndent = manifest.indent ?? '    '

  for (const block of manifest.blocks ?? []) {
    const rel = block.source.replace(/\\/g, '/')
    let raw
    if (virtual.has(rel)) {
      raw = virtual.get(rel)
    } else {
      const abs = path.join(pluginRoot, rel)
      if (!fs.existsSync(abs)) {
        throw new BuildError(`missing inlined source ${rel}`)
      }
      raw = fs.readFileSync(abs, 'utf8')
    }
    if (!built.includes(block.marker)) {
      throw new BuildError(`template ${manifest.template} is missing marker ${block.marker}`)
    }
    const stripped = stripModuleSyntax(raw, rel)
    const indented = indentBlock(stripped, block.indent ?? defaultIndent)
    // Use function replacement so `$` sequences in source code stay literal.
    built = built.replace(block.marker, () => indented)
  }

  const finalCode = assertCleanOutput(built, manifest.output)
  if (manifest.validateSyntax !== false) {
    assertValidScriptSyntax(finalCode, manifest.output)
  }
  files.push({ rel: manifest.output, content: finalCode })
  return { manifest, files }
}

/** Resolve the directory that directly holds plugin folders (workspace root or `plugins/`). */
export function pluginsBaseDir(workspaceRoot = WORKSPACE) {
  const nested = path.join(workspaceRoot, 'plugins')
  return fs.existsSync(nested) && fs.statSync(nested).isDirectory() ? nested : workspaceRoot
}

/** Discover all plugin directories containing `client/bundle.json`. */
export function discoverBundledPlugins(workspaceRoot = WORKSPACE) {
  const base = pluginsBaseDir(workspaceRoot)
  const found = []
  for (const entry of fs.readdirSync(base, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name.startsWith('.') || entry.name.startsWith('_')) continue
    const manifest = path.join(base, entry.name, 'client', 'bundle.json')
    if (fs.existsSync(manifest)) found.push(entry.name)
  }
  return found.sort()
}

export function processPlugin(pluginRoot, { checkOnly = false, label = path.basename(pluginRoot) } = {}) {
  const { files } = renderPluginBundle(pluginRoot)
  let stale = false

  for (const item of files) {
    const abs = path.join(pluginRoot, item.rel)
    if (checkOnly) {
      if (!fs.existsSync(abs)) {
        console.error(`${label}/${item.rel} is missing; run: node tools/build-client.mjs ${label}`)
        stale = true
        continue
      }
      const actual = fs.readFileSync(abs, 'utf8')
      if (actual !== item.content) {
        console.error(`${label}/${item.rel} is STALE: it does not match its sources.`)
        for (const msg of describeDifference(item.content, actual)) {
          console.error(msg)
        }
        console.error(`Run: node tools/build-client.mjs ${label}`)
        stale = true
      } else {
        console.log(`ok   ${label}/${item.rel} is up to date (${Buffer.byteLength(item.content, 'utf8')} bytes)`)
      }
    } else {
      fs.mkdirSync(path.dirname(abs), { recursive: true })
      fs.writeFileSync(abs, item.content, 'utf8')
      console.log(`built ${label}/${item.rel} (${Buffer.byteLength(item.content, 'utf8')} bytes)`)
    }
  }
  return stale ? 1 : 0
}

function main() {
  const args = process.argv.slice(2)
  const checkOnly = args.includes('--check')
  const rootIdx = args.indexOf('--root')
  const customRoot = rootIdx >= 0 ? args[rootIdx + 1] : undefined
  const positional = args.filter((a, i) => !a.startsWith('--') && (rootIdx < 0 || i !== rootIdx + 1))

  if (customRoot) {
    try {
      return processPlugin(path.resolve(customRoot), { checkOnly, label: path.basename(customRoot) })
    } catch (error) {
      console.error(error instanceof BuildError ? error.message : String(error))
      return 1
    }
  }

  const discovered = discoverBundledPlugins(WORKSPACE)
  const targets = positional.length > 0 ? positional : discovered
  if (targets.length === 0) {
    console.log('no plugins declare client/bundle.json')
    return 0
  }

  const baseDir = pluginsBaseDir(WORKSPACE)
  let exitCode = 0
  for (const name of targets) {
    const pluginRoot = path.join(baseDir, name)
    try {
      const code = processPlugin(pluginRoot, { checkOnly, label: name })
      if (code !== 0) exitCode = 1
    } catch (error) {
      console.error(`${name}: ${error instanceof BuildError ? error.message : String(error)}`)
      exitCode = 1
    }
  }
  return exitCode
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  process.exitCode = main()
}
